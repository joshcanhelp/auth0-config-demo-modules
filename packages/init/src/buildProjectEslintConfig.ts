import {
  ACTION_MODULE_GLOBALS,
  DATABASE_SCRIPT_GLOBALS,
  NODE_GLOBALS,
  RULES,
} from "auth0-config-demo-modules/packages/tenant-config/src/validate/utils/scriptEslint.js";

// Indents every line but the first, so a multi-line JSON block reads correctly once spliced
// into the template below instead of resetting to column 0 partway through.
function indent(json: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return json.split("\n").join(`\n${pad}`);
}

function literal(value: unknown, indentSpaces: number): string {
  return indent(JSON.stringify(value, null, 2), indentSpaces);
}

// Generated (not a static template) from the same RULES/globals `demo validate` lints Action
// and DB scripts with - see scriptEslint.ts. A rule or global added there starts showing up
// here the next time a project is scaffolded, with nothing to hand-copy or keep in sync.
export function buildProjectEslintConfig(): string {
  const rules = literal(RULES, 4);
  // A custom DB script's only top-level function is its entry point - Auth0's runtime calls
  // it directly, never by reference from within the file - so `no-unused-vars` would flag
  // every single script's entry function. `demo validate` filters that one specific message
  // back out at runtime (see lintDatabaseScriptCode in scriptEslint.ts); a static config has
  // no equivalent, so this rule is off here rather than permanently red for every DB script.
  const databaseRules = literal({ ...RULES, "no-unused-vars": "off" }, 4);
  const actionGlobals = literal(NODE_GLOBALS, 6);
  const actionModuleGlobals = literal({ ...NODE_GLOBALS, ...ACTION_MODULE_GLOBALS }, 6);
  const databaseGlobals = literal({ ...NODE_GLOBALS, ...DATABASE_SCRIPT_GLOBALS }, 6);

  return `// Generated by \`demo init\` - matches the rules \`demo validate\` runs against this
// project's Action and database connection scripts (auth0-config-demo-modules'
// validate/utils/scriptEslint.ts). Not overwritten on a later \`init\` run, so edit freely;
// re-scaffold into a fresh folder and copy this file over to pick up rule changes made there.
//
// Note: the database-connections block turns off no-unused-vars. \`demo validate\` applies it
// there too, but only after filtering out the one expected case (a DB script's un-exported
// entry-point function) - a static config can't express that filter, so it's off entirely
// here rather than flagging every DB script's entry function as unused.
export default [
  {
    files: ["tenants/*/actions/**/*.js"],
    languageOptions: {
      ecmaVersion: "latest",
      sourceType: "commonjs",
      globals: ${actionGlobals},
    },
    rules: ${rules},
  },
  {
    files: ["tenants/*/action-modules/**/*.js"],
    languageOptions: {
      ecmaVersion: "latest",
      sourceType: "commonjs",
      globals: ${actionModuleGlobals},
    },
    rules: ${rules},
  },
  {
    files: ["tenants/*/database-connections/**/*.js"],
    languageOptions: {
      ecmaVersion: "latest",
      sourceType: "commonjs",
      globals: ${databaseGlobals},
    },
    rules: ${databaseRules},
  },
];
`;
}
